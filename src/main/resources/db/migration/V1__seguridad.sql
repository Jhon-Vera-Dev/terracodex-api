-- Seguridad: roles, usuarios y sesiones (todo lo necesario para el login).
-- Maestros: cada columna lleva el nombre de la entidad (id_rol, descripcion_usuario) y las 4 columnas de auditoría.
-- Transaccionales (sesiones): columnas sin prefijo; solo sus FK a maestros siguen la regla.
-- Debe correr en H2 (modo PostgreSQL) y en PostgreSQL.

create table roles (
    id_rol                   bigint generated by default as identity primary key,
    descripcion_rol          varchar(60) not null unique,
    estado_rol               boolean     not null default true,
    usuario_creacion_rol     varchar(150) not null default 'SISTEMA',
    fecha_creacion_rol       timestamp with time zone not null default current_timestamp,
    usuario_modificacion_rol varchar(150) not null default 'SISTEMA',
    fecha_modificacion_rol   timestamp with time zone not null default current_timestamp
);

create table usuarios (
    id_usuario                   bigint generated by default as identity primary key,
    login_usuario                varchar(60)  not null unique,
    descripcion_usuario          varchar(150) not null,
    contrasena_usuario           varchar(100) not null,
    avatar_usuario               varchar(500),
    is_web_usuario               boolean      not null default true,
    is_movil_usuario             boolean      not null default false,
    estado_usuario               boolean      not null default true,
    usuario_creacion_usuario     varchar(150) not null default 'SISTEMA',
    fecha_creacion_usuario       timestamp with time zone not null default current_timestamp,
    usuario_modificacion_usuario varchar(150) not null default 'SISTEMA',
    fecha_modificacion_usuario   timestamp with time zone not null default current_timestamp
);

create table usuario_roles (
    id_usuario bigint not null references usuarios (id_usuario) on delete cascade,
    id_rol     bigint not null references roles (id_rol),
    primary key (id_usuario, id_rol)
);

-- Una fila por inicio de sesión. Su id viaja en el access token (claim sid); revocarla corta el acceso al instante.
create table sesiones (
    id           uuid primary key,
    id_usuario   bigint      not null references usuarios (id_usuario) on delete cascade,
    canal        varchar(10) not null,
    -- SHA-256 del refresh token; el valor en claro solo lo tiene el cliente
    refresh_hash varchar(64) not null unique,
    creada_en    timestamp with time zone not null,
    expira_en    timestamp with time zone not null,
    revocada_en  timestamp with time zone
);

create index ix_sesiones_usuario on sesiones (id_usuario);

