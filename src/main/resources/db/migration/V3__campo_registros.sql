-- Campo: registros de parcela hechos desde el móvil (ubicación, zona, riego y cultivo).
-- Transaccional: columnas sin prefijo de entidad, salvo la FK id_usuario. No se borran filas: se anulan (estado).
-- Debe correr en H2 (modo PostgreSQL) y en PostgreSQL.

create table registros_campo (
    id                   bigint generated by default as identity primary key,
    id_usuario           bigint           not null references usuarios (id_usuario),
    latitud              double precision not null,
    longitud             double precision not null,
    precision_metros     double precision,
    zona                 varchar(200),
    distrito             varchar(100),
    provincia            varchar(100),
    departamento         varchar(100),
    pais                 varchar(100),
    tipo_riego           varchar(10)      not null,
    cultivo_codigo       varchar(20),
    cultivo_descripcion  varchar(100)     not null,
    puntaje              double precision,
    sugerido             boolean          not null default false,
    observacion          varchar(500),
    fecha_registro       timestamp with time zone not null,
    estado               boolean          not null default true,
    usuario_creacion     varchar(150)     not null default 'SISTEMA',
    fecha_creacion       timestamp with time zone not null default current_timestamp,
    usuario_modificacion varchar(150)     not null default 'SISTEMA',
    fecha_modificacion   timestamp with time zone not null default current_timestamp,
    constraint ck_registros_campo_riego check (tipo_riego in ('SECANO', 'GRAVEDAD', 'GOTEO'))
);

create index ix_registros_campo_usuario_fecha on registros_campo (id_usuario, fecha_registro);
