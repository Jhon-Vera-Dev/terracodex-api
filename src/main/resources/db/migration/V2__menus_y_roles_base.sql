-- Menú de dos niveles: is_padre_menu agrupa opciones (sin path ni roles); las opciones tienen path y roles.
-- Maestro: columnas con el nombre de la entidad y las 4 columnas de auditoría.

create table menus (
    id_menu                   bigint generated by default as identity primary key,
    descripcion_menu          varchar(80)  not null,
    path_menu                 varchar(200),
    icon_menu                 varchar(40),
    orden_menu                integer      not null default 0,
    id_menu_padre             bigint references menus (id_menu),
    is_padre_menu             boolean      not null default false,
    is_web_menu               boolean      not null default true,
    is_movil_menu             boolean      not null default false,
    estado_menu               boolean      not null default true,
    usuario_creacion_menu     varchar(150) not null default 'SISTEMA',
    fecha_creacion_menu       timestamp with time zone not null default current_timestamp,
    usuario_modificacion_menu varchar(150) not null default 'SISTEMA',
    fecha_modificacion_menu   timestamp with time zone not null default current_timestamp
);

create table menu_roles (
    id_menu bigint not null references menus (id_menu) on delete cascade,
    id_rol  bigint not null references roles (id_rol),
    primary key (id_menu, id_rol)
);

-- Roles base además de ADMIN (V1). Sin ids explícitos para no desfasar las secuencias identity.
insert into roles (descripcion_rol) values ('SUPERVISOR'), ('OPERADOR');

-- Configuración del sistema: solo web y solo ADMIN
insert into menus (descripcion_menu, icon_menu, orden_menu, is_padre_menu, is_web_menu, is_movil_menu)
values ('Configuración', 'cog', 99, true, true, false);

insert into menus (descripcion_menu, path_menu, icon_menu, orden_menu, id_menu_padre, is_web_menu, is_movil_menu)
select v.descripcion, v.ruta, v.icono, v.orden,
       (select id_menu from menus where descripcion_menu = 'Configuración' and is_padre_menu), true, false
from (values
        ('Usuarios', '/seguridad/usuarios', 'users',  1),
        ('Roles',    '/seguridad/roles',    'shield', 2),
        ('Menús',    '/seguridad/menus',    'list',   3)
     ) as v (descripcion, ruta, icono, orden);

insert into menu_roles (id_menu, id_rol)
select m.id_menu, r.id_rol from menus m join roles r on r.descripcion_rol = 'ADMIN'
where m.path_menu like '/seguridad/%';
